// ----------------------------------------------------------------------------
//  调参的时候只改这里，不用去 .cpp 里翻。
//  每一项后面都写了"调大会怎样、调小会怎样"。
// ============================================================================
// ---------------- 1. 灰度阈值（threshold = 阈值）----------------
// 把彩色图转成灰度图以后，每个像素的亮度是 0 ~ 255。
// 比下面这个数字亮的像素，我们当成"可能是灯条"。
//   调大 → 只要最亮的，灯条会变短、远处的灯条会消失
//   调小 → 暗的东西也进来了，噪点变多
// 你的视频很暗：灯条大概 150~250，背景大概 0~30。100 比较稳。
const int GRAY_MIN = 100;
// ---------------- 2. 什么样的矩形算"灯条" ----------------
// 灯条 = 又细又长的一条。用矩形的宽、高来判断。
const int MIN_H = 12;      // 高度下限（像素）：太矮的不要（倒影、噪点）
const int MAX_H = 120;     // 高度上限
const int MIN_W = 2;       // 宽度下限
const int MAX_W = 60;      // 宽度上限
const int MIN_RATIO = 2;   // 高 ÷ 宽 至少是 2（细长）
// ---------------- 3. 两根灯条配成一块装甲板的规则 ----------------
// 同一块装甲板上的两根灯条：差不多高、差不多在同一水平线上、隔开一段距离。
const int MAX_H_DIFF = 22;   // 两根灯条的高度差（像素）
const int MAX_Y_DIFF = 28;   // 两根灯条的上边缘高度差（像素）
const int MIN_GAP = 20;      // 两根灯条的水平间距下限
const int MAX_GAP = 170;     // 上限
// ---------------- 4. 地面倒影的规则 ----------------
// 倒影在灯条正下方，左右位置几乎一样，而且比灯条矮。
const int SHADOW_X_DIFF = 14;   // "左右位置差不多"的容忍度（像素）